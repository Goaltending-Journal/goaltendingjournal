"""Build goalies-zones-data.js for the zone heat map on goalies.html.

Inputs are two MoneyPuck-format CSVs for one season:
  - a shot file (one row per unblocked shot attempt, with arena-adjusted x/y)
  - a goalie game-by-game file (one row per goalie, game and situation)

Usage:
  python build_zone_data.py "2026 Shot Data.csv" "2026 Goalie Data.csv"

Only games present in both files are used, so the map and the goalie totals
cover the same games. Empty-net shots are left out. Save % in a zone is
1 - goals / shots on goal, where shots on goal include goals.
"""

import csv
import json
import sys
from collections import defaultdict
from datetime import date
from pathlib import Path

OUT = Path(__file__).resolve().parent / "goalies-zones-data.js"

# Regions in attacking-zone coordinates: X is feet from centre ice toward the
# goal (goal line at 89, blue line at 25), Y is feet across the ice, with the
# sign flipped for shots at the other end so every shot faces the same goal.
ZONES = [
    ("behind", "Behind the net"),
    ("crease", "Crease"),
    ("lowslot", "Low slot"),
    ("highslot", "High slot"),
    ("lowL", "Low wing (left)"),
    ("lowR", "Low wing (right)"),
    ("circL", "Upper circle (left)"),
    ("circR", "Upper circle (right)"),
    ("pointL", "Left point"),
    ("pointC", "Centre point"),
    ("pointR", "Right point"),
    ("long", "Outside the zone"),
]


def zone_of(x: float, y: float) -> str:
    """Left and right are as drawn on the map (positive Y on the left)."""
    if x > 89:
        return "behind"
    if x < 25:
        return "long"
    if x >= 69:
        if abs(y) <= 8:
            return "crease" if x >= 80 else "lowslot"
        return "lowL" if y > 0 else "lowR"
    if x >= 54:
        if abs(y) <= 10:
            return "highslot"
        return "circL" if y > 0 else "circR"
    if y > 15:
        return "pointL"
    if y < -15:
        return "pointR"
    return "pointC"


def main(shot_path: str, goalie_path: str) -> int:
    with open(goalie_path, newline="", encoding="utf-8") as f:
        games = [r for r in csv.DictReader(f) if r["situation"] == "all"]
    with open(shot_path, newline="", encoding="utf-8") as f:
        shots = list(csv.DictReader(f))

    # Shot file game_id is 20001; game file gameId is 2026020001.
    game_ids = {int(r["gameId"]) % 1_000_000 for r in games}
    goalies = {}
    for r in games:
        g = goalies.setdefault(r["playerId"], {
            "id": int(r["playerId"]), "name": r["name"], "team": r["playerTeam"],
            "gp": 0, "toi": 0.0, "sog": 0.0, "ga": 0.0, "xga": 0.0, "last": "",
        })
        g["gp"] += 1
        g["toi"] += float(r["icetime"])
        g["sog"] += float(r["ongoal"])
        g["ga"] += float(r["goals"])
        g["xga"] += float(r["xGoals"])
        if r["gameDate"] >= g["last"]:
            g["last"], g["team"] = r["gameDate"], r["playerTeam"]

    zone_counts = defaultdict(lambda: defaultdict(lambda: [0, 0]))
    league = defaultdict(lambda: [0, 0])
    used = 0
    for s in shots:
        if int(s["game_id"]) not in game_ids:
            continue
        if s["shotWasOnGoal"] != "1.0" or s["shotOnEmptyNet"] == "1":
            continue
        x, y = float(s["arenaAdjustedXCord"]), float(s["arenaAdjustedYCord"])
        if x < 0:
            x, y = -x, -y
        z = zone_of(x, y)
        goal = int(s["goal"])
        for bucket in (zone_counts[s["goalieIdForShot"]][z], league[z]):
            bucket[0] += 1
            bucket[1] += goal
        used += 1

    dates = sorted(r["gameDate"] for r in games)
    out_goalies = []
    for pid, g in goalies.items():
        out_goalies.append({
            "id": g["id"], "name": g["name"], "team": g["team"], "gp": g["gp"],
            "toi": round(g["toi"] / 60), "sog": int(g["sog"]), "ga": int(g["ga"]),
            "xga": round(g["xga"], 2),
            "z": {k: v for k, v in zone_counts[pid].items()},
        })
    out_goalies.sort(key=lambda g: g["name"].split(" ", 1)[-1])

    fmt = lambda d: date(int(d[:4]), int(d[4:6]), int(d[6:])).isoformat()
    data = {
        "season": "2026-27",
        "from": fmt(dates[0]),
        "to": fmt(dates[-1]),
        "games": len(game_ids),
        "shots": used,
        "credit": "Shot and goalie data in MoneyPuck.com's published format (https://moneypuck.com)",
        "zones": [{"id": k, "name": n} for k, n in ZONES],
        "league": {k: league[k] for k, _ in ZONES},
        "goalies": out_goalies,
    }
    OUT.write_text(
        "/* Generated by build_zone_data.py. Zone save % for the heat map on goalies.html. */\n"
        "window.GOALIE_ZONES = " + json.dumps(data, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    print(f"Wrote {OUT.name}: {used} shots on goal, {len(game_ids)} games, {len(out_goalies)} goalies")
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    sys.exit(main(sys.argv[1], sys.argv[2]))
